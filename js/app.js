//  Перевірка підключення
console.log("script.js успішно підключено!");

//  Оголошення даних (Масив об'єктів прогнозу на 7 днів)
const forecastData = [
  { day: "Пн", temp: 18 },
  { day: "Вв", temp: 22 },
  { day: "Ср", temp: 15 },
  { day: "Чт", temp: -2 }, // Додаємо морозний день для перевірки
  { day: "Пт", temp: 0 },
  { day: "Сб", temp: -5 }, // Ще один морозний день
  { day: "Нд", temp: 5 },
];

//  Стрілкова функція для конвертації температури
// Приймає градуси Цельсія (c), повертає Фаренгейти
const toFahrenheit = (c) => (c * 9) / 5 + 32;

//  Обробка даних циклом for...of та умовна класифікація
console.log("--- Прогноз погоди на тиждень ---");

// Функція для виведення прогнозу
function displayForecast(forecastArray) {
  // Цикл for...of проходить по кожному об'єкту (dayData) в масиві
  for (const dayData of forecastArray) {
    // Використовуємо стрілкову функцію
    const tempF = toFahrenheit(dayData.temp);

    // Змінна для збереження додаткового повідомлення
    let status = "";

    // Умова: якщо температура нижче 0, позначаємо як "морозно"
    if (dayData.temp < 0) {
      status = "(морозно ❄️)";
    } else {
      status = "(тепло ☀️)";
    }

    // Виводимо результат у консоль, використовуючи шаблонні рядки (зворотні лапки `)
    console.log(
      `День: ${dayData.day}, Температура: ${dayData.temp}°C / ${tempF}°F ${status}`,
    );
  }
}

// Викликаємо функцію, передаючи їй наш масив
displayForecast(forecastData);
